export function measure(text: string, scale: number): number {
  return text.length * GLYPH_ADVANCE * scale;
}

/**
 * Appends `text` to `out` as flat 2D line-segment pairs (x0,y0,x1,y1,…).
 * Unknown characters fall back to a dotted placeholder rather than vanishing,
 * so a bad string is visible during development instead of silently blank.
 */
export function appendText(
  out: number[],
  text: string,
  x: number,
  y: number,
  scale: number,
): void {
  let cursor = x;
  for (const raw of text.toUpperCase()) {
    const glyph = G[raw] ?? G["-"];
    for (const line of glyph) {
      for (let i = 0; i < line.length - 1; i++) {
        out.push(
          cursor + line[i][0] * scale,
          y + line[i][1] * scale,
          cursor + line[i + 1][0] * scale,
          y + line[i + 1][1] * scale,
        );
      }
    }
    cursor += GLYPH_ADVANCE * scale;
  }
}
